-- NOTES / JOURNAL
create table if not exists notes (
  id          uuid primary key default gen_random_uuid(),
  title       text,
  content     text not null,
  image_url   text,
  likes       integer not null default 0,
  created_at  timestamptz not null default now()
);

-- GALLERY
create table if not exists gallery (
  id          uuid primary key default gen_random_uuid(),
  url         text not null,
  title       text,
  caption     text,
  likes       integer not null default 0,
  created_at  timestamptz not null default now()
);

-- SNIPPETS
create table if not exists snippets (
  id          uuid primary key default gen_random_uuid(),
  title       text not null,
  description text,
  language    text not null default 'js',
  code        text not null,
  views       integer not null default 0,
  likes       integer not null default 0,
  created_at  timestamptz not null default now()
);

-- MUSIC
create table if not exists music (
  id          uuid primary key default gen_random_uuid(),
  title       text not null,
  artist      text not null,
  duration    text,
  url         text,
  thumbnail   text,
  lyrics      text,
  added_at    timestamptz not null default now()
);

-- GUESTBOOK (public messages, threaded replies, admin moderation)
-- owner_token: random secret generated client-side at post time, kept only in
-- the poster's own localStorage, and required (matched server-side) to allow
-- a non-admin delete of their own message. Never exposed to other visitors.
create table if not exists guestbook (
  id           uuid primary key default gen_random_uuid(),
  name         text not null,
  message      text not null,
  parent_id    uuid references guestbook(id) on delete cascade,
  is_admin     boolean not null default false,
  likes        integer not null default 0,
  owner_token  uuid not null default gen_random_uuid(),
  created_at   timestamptz not null default now()
);
create index if not exists guestbook_parent_idx on guestbook(parent_id);

-- SETTINGS (passphrase hash, dll)
create table if not exists settings (
  key         text primary key,
  value       text not null,
  updated_at  timestamptz not null default now()
);

